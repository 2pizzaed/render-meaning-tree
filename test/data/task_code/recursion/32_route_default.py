# Маршрут по умолчанию накапливается между вызовами функции
def visit(city, route=[]):
    route.append(city)
    if len(route) > 2:  # <! FFT >
        print("маршрут слишком длинный:", route)

visit("Казань")  # <! (-, "visit('Казань', [])") >
visit("Пермь")  # <! (-, "visit('Пермь', ['Казань'])") >
visit("Уфа")  # <! (-, "visit('Уфа', ['Казань', 'Пермь'])") >
